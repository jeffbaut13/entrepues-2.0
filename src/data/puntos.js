export const VIDEO_SCROLL_POINTS_FLAT = VIDEO_SCROLL_CHECKPOINTS.flatMap(
  (checkpoint) =>
    checkpoint.puntos.map((point) => {
      const start = Number(point.timeShow ?? checkpoint.time);
      const rawTimeout = Number(point.timeout ?? 0);
      const end = rawTimeout > start ? rawTimeout : start + rawTimeout;

      return {
        ...point,
        region: regionToSlug(point.region),
        checkpoint: checkpoint.checkpoint,
        checkpointTime: checkpoint.time,
        checkpointFrame: checkpoint.frame,
        timeShow: start,
        timeout: end,
      };
    }),
);

