export const VIDEO_SCROLL_TIMELINE = {
  frameCount: 677,
  durationSeconds: 56.41,
};

const capitalizeWords = (value = "") =>
  String(value)
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");

export const normalizeRegionName = (value = "") =>
  String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const REGION_ALIASES = {
  "pet family": "pet-family",
  petFamily: "pet-family",
  general: "general",
};

export const regionToSlug = (value = "") => {
  const normalized = normalizeRegionName(value);
  if (!normalized) return "general";

  const direct = REGIONES.find(
    (region) =>
      normalizeRegionName(region.slug) === normalized ||
      normalizeRegionName(region.title) === normalized,
  );
  if (direct) return direct.slug;

  if (REGION_ALIASES[normalized]) return REGION_ALIASES[normalized];

  return normalized.replace(/\s+/g, "-");
};

export const getRegionBySlug = (slug = "") => {
  const target = regionToSlug(slug);
  return REGIONES.find((region) => region.slug === target) || null;
};

export const formatRegionLabel = (value = "", fallback = "Zona general") => {
  const slug = regionToSlug(value);
  if (slug === "general") return fallback;

  const region = getRegionBySlug(slug);
  if (region) return region.title;

  return capitalizeWords(String(value).replace(/[-_]+/g, " "));
};

export const timeToFrame = (timeInSeconds) => {
  const frame =
    (Number(timeInSeconds || 0) / VIDEO_SCROLL_TIMELINE.durationSeconds) *
    (VIDEO_SCROLL_TIMELINE.frameCount - 1);

  return Math.max(
    0,
    Math.min(VIDEO_SCROLL_TIMELINE.frameCount - 1, Math.round(frame)),
  );
};

export const frameToTime = (frame) => {
  const safeFrame = Math.max(
    0,
    Math.min(VIDEO_SCROLL_TIMELINE.frameCount - 1, Number(frame || 0)),
  );

  return (
    (safeFrame / (VIDEO_SCROLL_TIMELINE.frameCount - 1)) *
    VIDEO_SCROLL_TIMELINE.durationSeconds
  );
};

